/**
 * SEO Sync Controller — BlueAgle
 * Exposes API endpoints that drive the SEO Sync Engine.
 * All endpoints require verifyAdminToken + SEO permission.
 */

const { runSeoSync, STATIC_PAGES } = require('../services/seoSyncEngine');
const { SeoSetting, SeoAuditLog, Product, Category, SubCategory } = require('../models');
const { Op } = require('sequelize');

// POST /api/seo/sync/generate
// Generate missing SEO records (safe, idempotent, does not overwrite manual edits)
const generateMissingSeo = async (req, res) => {
    try {
        const triggeredBy = req.user?.email || 'admin';
        const report = await runSeoSync({
            onlyMissing: true,
            overwriteAuto: false,
            skipManual: true,
            dryRun: false,
            triggeredBy,
        });

        await SeoAuditLog.create({
            pageKey: '__SYNC__',
            action: 'SYNC_GENERATE_MISSING',
            performedBy: triggeredBy,
            changes: {
                scanned: report.scanned,
                created: report.created,
                skipped: report.skipped,
                skippedManual: report.skippedManual,
                executionTimeMs: report.executionTimeMs,
            },
        });

        res.json({
            success: true,
            message: `SEO sync complete. Created ${report.created} new records.`,
            report,
        });
    } catch (err) {
        console.error('[SEO Sync] generateMissingSeo error:', err);
        res.status(500).json({ success: false, message: err.message });
    }
};

// POST /api/seo/sync/regenerate
// Regenerate SEO with options passed in body
// body: { onlyMissing, overwriteAuto, skipManual, dryRun }
const regenerateSeo = async (req, res) => {
    try {
        const {
            onlyMissing = false,
            overwriteAuto = true,
            skipManual = true,
            dryRun = false,
        } = req.body;

        const triggeredBy = req.user?.email || 'admin';
        const report = await runSeoSync({
            onlyMissing,
            overwriteAuto,
            skipManual,
            dryRun,
            triggeredBy,
        });

        if (!dryRun) {
            await SeoAuditLog.create({
                pageKey: '__SYNC__',
                action: 'SYNC_REGENERATE',
                performedBy: triggeredBy,
                changes: {
                    scanned: report.scanned,
                    created: report.created,
                    updated: report.updated,
                    skipped: report.skipped,
                    skippedManual: report.skippedManual,
                    executionTimeMs: report.executionTimeMs,
                    options: { onlyMissing, overwriteAuto, skipManual, dryRun },
                },
            });
        }

        res.json({
            success: true,
            dryRun,
            message: dryRun
                ? `Dry run complete. Would create ${report.created}, update ${report.updated}, skip ${report.skipped}.`
                : `Regeneration complete. Created ${report.created}, updated ${report.updated}.`,
            report,
        });
    } catch (err) {
        console.error('[SEO Sync] regenerateSeo error:', err);
        res.status(500).json({ success: false, message: err.message });
    }
};

