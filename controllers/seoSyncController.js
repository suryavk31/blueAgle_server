// GET /api/seo/sync/missing
// Returns list of pages that have no SEO record yet
const getMissingPages = async (req, res) => {
    try {
        const report = await runSeoSync({
            onlyMissing: true,
            dryRun: true,
            triggeredBy: 'check',
        });

        const missing = report.pages.filter(p => p.action === 'CREATE');
        res.json({
            success: true,
            totalMissing: missing.length,
            totalScanned: report.scanned,
            pages: missing,
        });
    } catch (err) {
        res.status(500).json({ success: false, message: err.message });
    }
};

// GET /api/seo/sync/stats
// Returns dashboard statistics for SEO sync panel
const getSyncStats = async (req, res) => {
    try {
        const total = await SeoSetting.count();
        const autoGenerated = await SeoSetting.count({ where: { isAutoGenerated: true } });
        const manuallyEdited = await SeoSetting.count({ where: { isManuallyEdited: true } });
        const indexed = await SeoSetting.count({ where: { isIndexed: true } });
        const noIndex = await SeoSetting.count({ where: { isIndexed: false } });

        // Count by page type
        const byType = await SeoSetting.findAll({
            attributes: ['pageType', [require('sequelize').fn('COUNT', require('sequelize').col('id')), 'count']],
            group: ['pageType'],
            raw: true,
        });

        // Scan to find how many pages are missing
        const missingReport = await runSeoSync({ onlyMissing: true, dryRun: true, triggeredBy: 'stats' });
        const missingCount = missingReport.pages.filter(p => p.action === 'CREATE').length;

        // Recent sync logs
        const recentLogs = await SeoAuditLog.findAll({
            where: { action: { [Op.in]: ['SYNC_GENERATE_MISSING', 'SYNC_REGENERATE', 'AUTO_SYNC_CREATE', 'AUTO_SYNC_UPDATE'] } },
            order: [['createdAt', 'DESC']],
            limit: 10,
        });

        res.json({
            success: true,
            stats: {
                total,
                autoGenerated,
                manuallyEdited,
                indexed,
                noIndex,
                missingCount,
                byType,
            },
            recentLogs,
        });
    } catch (err) {
        res.status(500).json({ success: false, message: err.message });
    }
};

// POST /api/seo/sync/mark-manual/:id
// Mark a record as manually edited (prevents auto-sync overwrite)
const markAsManual = async (req, res) => {
    try {
        const { id } = req.params;
        const record = await SeoSetting.findByPk(id);
        if (!record) return res.status(404).json({ message: 'SEO record not found' });

        await record.update({ isManuallyEdited: true, updatedBy: req.user?.email || 'admin' });
        res.json({ success: true, message: 'Marked as manually edited. Auto-sync will skip this record.' });
    } catch (err) {
        res.status(500).json({ success: false, message: err.message });
    }
};

// DELETE /api/seo/sync/mark-manual/:id
// Unmark manual edit (allows auto-sync to update again)
const unmarkManual = async (req, res) => {
    try {
        const { id } = req.params;
        const record = await SeoSetting.findByPk(id);
        if (!record) return res.status(404).json({ message: 'SEO record not found' });

        await record.update({ isManuallyEdited: false, updatedBy: req.user?.email || 'admin' });
        res.json({ success: true, message: 'Manual edit flag cleared. Auto-sync can now update this record.' });
    } catch (err) {
        res.status(500).json({ success: false, message: err.message });
    }
};

module.exports = {
    generateMissingSeo,
    regenerateSeo,
    previewSync,
    getMissingPages,
    getSyncStats,
    markAsManual,
    unmarkManual,
};
